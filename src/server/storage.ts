import "server-only";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import { dirname, join, resolve, sep } from "node:path";

/**
 * FILE STORAGE on the project's own disk: `<project>/uploads` (media, documents, resumes), next to `uploads/banners` and `uploads/products`.
 * No bucket and no cloud service. The folder is git-ignored and is never served as static files: the bytes are only read back through
 * our own routes, after a permission check. Object keys are random (never derived from the file name).
 *
 * `getStorage()` always gives the local disk; it is null only when a test switches storage off.
 */
export interface StoredObject {
  stream: ReadableStream<Uint8Array>;
  contentType?: string;
  contentLength?: number;
}

export interface ObjectStorage {
  put(key: string, body: Buffer, opts: { contentType: string }): Promise<void>;
  get(key: string): Promise<StoredObject>;
  delete(key: string): Promise<void>;
}

/** Content-Disposition value that is safe for any file name (RFC 6266 / 5987). */
export function attachmentDisposition(fileName: string): string {
  const ascii = fileName.replace(/[^\x20-\x7e]/g, "_").replace(/["\\]/g, "_");
  return `attachment; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(fileName)}`;
}

/** Where uploaded files live: the project's own `uploads` folder (override with UPLOAD_DIR). Git-ignored, never served as static files. */
export const uploadRoot = () => resolve(process.env.UPLOAD_DIR?.trim() || join(/*turbopackIgnore: true*/ process.cwd(), "uploads"));

/** Keys are generated by the server (`media/2026/<uuid>.png`); anything else is refused so a key can never leave the folder. */
const KEY = /^[a-z]+(?:\/\d{4})?\/[0-9a-f-]{8,40}\.[a-z0-9]{1,8}$/;
function pathOf(key: string): string {
  if (!KEY.test(key)) throw new Error("Invalid storage key");
  const root = uploadRoot();
  const full = resolve(root, key);
  if (!full.startsWith(root + sep)) throw new Error("Invalid storage key");
  return full;
}
const notFound = () => Object.assign(new Error("File not found"), { name: "NoSuchKey" });

export async function readLocalFile(key: string): Promise<Buffer> {
  try {
    return await readFile(pathOf(key));
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === "ENOENT") throw notFound();
    throw e;
  }
}

export function createLocalStorage(): ObjectStorage {
  return {
    async put(key, body) {
      const full = pathOf(key);
      await mkdir(dirname(full), { recursive: true });
      await writeFile(full, body, { flag: "wx" }); // never overwrites an existing file
    },
    async get(key) {
      const bytes = await readLocalFile(key);
      return { stream: new Response(new Uint8Array(bytes)).body as ReadableStream<Uint8Array>, contentLength: bytes.length };
    },
    async delete(key) {
      await unlink(pathOf(key)).catch((e: NodeJS.ErrnoException) => {
        if (e.code !== "ENOENT") throw e;
      });
    },
  };
}

let override: ObjectStorage | null | undefined;
let cached: ObjectStorage | null | undefined;

/** Test hook: force a storage implementation (or null), or pass undefined to re-read the environment. */
export function setStorageForTests(storage: ObjectStorage | null | undefined) {
  override = storage;
  cached = undefined;
}

export function getStorage(): ObjectStorage | null {
  if (override !== undefined) return override;
  if (cached !== undefined) return cached;
  cached = createLocalStorage();
  return cached;
}

export const isStorageConfigured = () => getStorage() !== null;
